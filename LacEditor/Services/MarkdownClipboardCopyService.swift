/// A limited, source-mapped projection of one selection from the full document.
enum MarkdownClipboardCopyService {
    struct EmbeddedImage {
        let image: MarkdownImageUploadService.Image
        let data: Data
        let mime: String
        let filename: String
    }

    static func embeddedImages(in markdown: String, allowingExternal: Bool = false,
                               isCancelled: @escaping () -> Bool = { false }) throws -> [EmbeddedImage] {
        if isCancelled() { throw CancellationError() }
        let images = try MarkdownImageUploadService.images(in: markdown, isCancelled: isCancelled)
        return try images.compactMap { image in
            if isCancelled() { throw CancellationError() }
            guard image.syntax == .markdown else {
                throw MarkdownImageUploadService.UploadError.unsupportedImage
            }
            if allowingExternal, let url = URL(string: image.address) {
                if ["http", "https"].contains(url.scheme?.lowercased() ?? ""), url.host != nil { return nil }
                if url.isFileURL, url.host == nil || url.host == "" || url.host == "localhost" { return nil }
            }
            guard image.address.hasPrefix("data:") else { throw MarkdownImageUploadService.UploadError.unsupportedImage }
            let payload = try MarkdownImageUploadService.payload(address: image.address, document: nil)
            return EmbeddedImage(image: image, data: payload.data, mime: payload.mime, filename: payload.filename)
        }
    }

    static func replacingEmbeddedImages(in markdown: String, images: [EmbeddedImage], addresses: [URL]) throws -> String {
        guard !images.isEmpty, images.count == addresses.count else { throw MarkdownImageUploadService.UploadError.invalidInput }
        let edit = try MarkdownImageUploadService.replacement(in: markdown, images: images.map(\.image), urls: addresses,
                                                               selection: NSRange(location: 0, length: 0))
        return (markdown as NSString).replacingCharacters(in: edit.range, with: edit.replacement)
    }

    /// This accepts only the fixed, escaped HTML generated by `project`.
    @MainActor
    static func structuralRTF(_ fragment: Fragment) async -> Data? {
        guard !fragment.hasUnverifiedHTMLBlocks else { return nil }
        let table = fragment.html.contains("<table>")
        let list = fragment.html.contains("<ul>") || fragment.html.contains("<ol ")
        let quote = fragment.html.contains("<blockquote>")
        if table && fragment.html.contains(" align=\"") { return nil }
        let headings = (1...6).filter { fragment.html.contains("<h\($0)>") }
        if fragment.html.contains("<pre><code"), table || list || quote { return nil }
        let imageCount = fragment.html.components(separatedBy: "<img src=\"").count - 1
        guard fragment.imageLinks.count == imageCount else { return nil }
        guard table || list || quote || !headings.isEmpty || imageCount > 0 else { return nil }
        guard !(quote && table) else { return nil }
        if !headings.isEmpty {
            guard headings.count == 1, !table, !list, !quote,
                  let level = headings.first, fragment.html.hasPrefix("<h\(level)>"), fragment.html.hasSuffix("</h\(level)>"),
                  fragment.html.components(separatedBy: "<h\(level)>").count == 2 else { return nil }
        }
        var quoteDepth = 0, maximumQuoteDepth = 0
        if quote {
            let tags = try? NSRegularExpression(pattern: "</?blockquote>")
            let html = fragment.html as NSString
            let matches = tags?.matches(in: fragment.html, range: NSRange(location: 0, length: html.length)) ?? []
            guard let first = matches.first, first.range.location == 0, let last = matches.last,
                  NSMaxRange(last.range) == html.length else { return nil }
            for (index, match) in matches.enumerated() {
                if html.substring(with: match.range).hasPrefix("</") { quoteDepth -= 1 }
                else { quoteDepth += 1; maximumQuoteDepth = max(maximumQuoteDepth, quoteDepth) }
                guard quoteDepth >= 0, quoteDepth > 0 || index == matches.count - 1 else { return nil }
            }
            guard quoteDepth == 0, !list || maximumQuoteDepth == 1 else { return nil }
        }
        var quoteAnchor: String?
        if quote && list {
            let body = String(fragment.html.dropFirst("<blockquote>".count))
            guard !body.hasPrefix("<ul>"), !body.hasPrefix("<ol "),
                  let first = fragment.text.components(separatedBy: "\n").first, first.hasPrefix("> ") else { return nil }
            let anchor = String(first.dropFirst(2))
            guard !anchor.isEmpty else { return nil }
            quoteAnchor = anchor
        }
        let body = fragment.html
            .replacingOccurrences(of: "<input type=\"checkbox\" disabled checked>", with: "☑")
            .replacingOccurrences(of: "<input type=\"checkbox\" disabled>", with: "☐")
        let remoteImages = try? NSRegularExpression(pattern: "(<img src=\")https?://[^\"]*(\")", options: .caseInsensitive)
        let safeBody = remoteImages?.stringByReplacingMatches(in: body, range: NSRange(location: 0, length: (body as NSString).length), withTemplate: "$1data:,$2") ?? body
        let html = "<!doctype html><html><head><meta charset=\"utf-8\"></head><body>" + safeBody + "</body></html>"
        guard let (attributed, _) = try? await NSAttributedString.fromHTML(Data(html.utf8)), !Task.isCancelled else { return nil }
        guard let data = try? attributed.data(from: NSRange(location: 0, length: attributed.length), documentAttributes: [.documentType: NSAttributedString.DocumentType.rtf]),
              let restored = try? NSAttributedString(data: data, options: [.documentType: NSAttributedString.DocumentType.rtf], documentAttributes: nil) else { return nil }
        let tags = try? NSRegularExpression(pattern: "<(?:ul>|ol [^>]*>|/ul>|/ol>)")
        let htmlSource = fragment.html as NSString
        var depth = 0, requiredDepth = 0
        for match in tags?.matches(in: fragment.html, range: NSRange(location: 0, length: htmlSource.length)) ?? [] {
            if htmlSource.substring(with: match.range).hasPrefix("</") { depth -= 1 }
            else { depth += 1; requiredDepth = max(requiredDepth, depth) }
        }
        var hasTable = false, listDepth = 0, hasQuoteIndent = false, hasHeadingFont = restored.length > 0
        restored.enumerateAttribute(.paragraphStyle, in: NSRange(location: 0, length: restored.length)) { value, _, _ in
            guard let style = value as? NSParagraphStyle else { return }
            hasTable = hasTable || style.textBlocks.contains { $0 is NSTextTableBlock }
            listDepth = max(listDepth, style.textLists.count)
            hasQuoteIndent = hasQuoteIndent || style.headIndent > 0 || style.firstLineHeadIndent > 0
        }
        if let quoteAnchor {
            let text = restored.string as NSString
            var cursor = 0, firstParagraph: NSRange?
            while cursor < text.length {
                let range = text.paragraphRange(for: NSRange(location: cursor, length: 0))
                if !text.substring(with: range).trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { firstParagraph = range; break }
                guard NSMaxRange(range) > cursor else { break }
                cursor = NSMaxRange(range)
            }
            guard let range = firstParagraph,
                  text.substring(with: range).trimmingCharacters(in: .whitespacesAndNewlines) == quoteAnchor,
                  let style = restored.attribute(.paragraphStyle, at: range.location, effectiveRange: nil) as? NSParagraphStyle,
                  style.textLists.isEmpty, style.headIndent > 0 || style.firstLineHeadIndent > 0 else { return nil }
        }
        if maximumQuoteDepth > 1 {
            let lines = fragment.text.components(separatedBy: "\n")
            var expected = "", ranges: [(NSRange, Int)] = []
            for (index, line) in lines.enumerated() {
                if index > 0 { expected += "\n" }
                var value = line, depth = 0
                while value.hasPrefix("> ") { value.removeFirst(2); depth += 1 }
                guard depth > 0 || value.isEmpty else { return nil }
                let start = (expected as NSString).length
                expected += value
                if !value.isEmpty { ranges.append((NSRange(location: start, length: (value as NSString).length), depth)) }
            }
            let expectedText = expected as NSString, actualText = restored.string as NSString
            func contentRange(_ text: NSString) -> NSRange {
                var start = 0, end = text.length
                while start < end && (text.character(at: start) == 10 || text.character(at: start) == 13) { start += 1 }
                while end > start && (text.character(at: end - 1) == 10 || text.character(at: end - 1) == 13) { end -= 1 }
                return NSRange(location: start, length: end - start)
            }
            let expectedRange = contentRange(expectedText), actualRange = contentRange(actualText)
            guard expectedText.substring(with: expectedRange) == actualText.substring(with: actualRange) else { return nil }
            var indents: [Int: (CGFloat, CGFloat)] = [:]
            for (range, depth) in ranges {
                guard range.location >= expectedRange.location, NSMaxRange(range) <= NSMaxRange(expectedRange) else { return nil }
                let mapped = NSRange(location: actualRange.location + range.location - expectedRange.location, length: range.length)
                restored.enumerateAttribute(.paragraphStyle, in: mapped) { value, _, _ in
                    let style = value as? NSParagraphStyle
                    let indent = max(style?.headIndent ?? 0, style?.firstLineHeadIndent ?? 0)
                    let old = indents[depth] ?? (indent, indent)
                    indents[depth] = (min(old.0, indent), max(old.1, indent))
                }
            }
            for depth in 1...maximumQuoteDepth {
                guard let current = indents[depth], current.0 > 0 else { return nil }
                if depth > 1, let parent = indents[depth - 1], current.0 <= parent.1 { return nil }
                if depth > 1 && indents[depth - 1] == nil { return nil }
            }
        }
        restored.enumerateAttribute(.font, in: NSRange(location: 0, length: restored.length)) { value, _, _ in
            guard let font = value as? NSFont, NSFontManager.shared.traits(of: font).contains(.boldFontMask) else { hasHeadingFont = false; return }
        }
        func imageLinks(in text: NSAttributedString) -> [String?] {
            var result: [String?] = []
            text.enumerateAttribute(.attachment, in: NSRange(location: 0, length: text.length)) { value, range, _ in
                guard value is NSTextAttachment else { return }
                let link = text.attribute(.link, at: range.location, effectiveRange: nil)
                result.append((link as? URL)?.absoluteString ?? (link as? String))
            }
            return result
        }
        let originalImageLinks = imageLinks(in: attributed), restoredImageLinks = imageLinks(in: restored)
        var images = 0
        restored.enumerateAttribute(.attachment, in: NSRange(location: 0, length: restored.length)) { value, _, _ in
            guard let attachment = value as? NSTextAttachment else { return }
            if attachment.image != nil || attachment.fileWrapper?.regularFileContents.flatMap(NSImage.init(data:)) != nil { images += 1 }
        }
        if !headings.isEmpty || (quote && !list && !table && !fragment.html.contains("<pre><code")) {
            guard exactStructuralText(fragment.structuralParts, matches: attributed.string),
                  exactStructuralText(fragment.structuralParts, matches: restored.string) else { return nil }
        }
        if quote && !list && !table && !fragment.html.contains("<pre><code") {
            guard quoteIndentMatches(fragment.structuralParts, text: attributed),
                  quoteIndentMatches(fragment.structuralParts, text: restored) else { return nil }
        }
        guard (!table || hasTable), (!list || listDepth >= requiredDepth && requiredDepth > 0),
              (!quote || hasQuoteIndent), (headings.isEmpty || hasHeadingFont), images >= imageCount,
              originalImageLinks == fragment.imageLinks, restoredImageLinks == fragment.imageLinks else { return nil }
        return data
    }

    static func exactStructuralText(_ parts: [Fragment.StructuralPart], matches actual: String) -> Bool {
        structuralTextStart(parts, in: actual) != nil
    }

    private static func structuralTextStart(_ parts: [Fragment.StructuralPart], in actual: String) -> Int? {
        var expected = ""
        for part in parts {
            switch part.kind {
            case .text, .lineBreak, .taskMarker: expected += part.text
            case .image: expected += "\u{fffc}"
            case .thematicBreak: return nil
            default: break
            }
        }
        if expected == actual { return 0 }
        // HTML importers can add paragraph separators at the edges of a document.
        let units = actual as NSString, expectedUnits = expected as NSString
        var start = 0, end = units.length
        if expectedUnits.length == 0 || expectedUnits.character(at: 0) != 10 {
            while start < end && (units.character(at: start) == 10 || units.character(at: start) == 13) { start += 1 }
        }
        if expectedUnits.length == 0 || expectedUnits.character(at: expectedUnits.length - 1) != 10 {
            while end > start && (units.character(at: end - 1) == 10 || units.character(at: end - 1) == 13) { end -= 1 }
        }
        return units.substring(with: NSRange(location: start, length: end - start)) == expected ? start : nil
    }

    static func quoteIndentMatches(_ parts: [Fragment.StructuralPart], text: NSAttributedString) -> Bool {
        guard var cursor = structuralTextStart(parts, in: text.string) else { return false }
        for part in parts {
            let length: Int
            switch part.kind {
            case .text, .lineBreak, .taskMarker: length = (part.text as NSString).length
            case .image: length = 1
            default: continue
            }
            let range = NSRange(location: cursor, length: length)
            cursor += length
            guard part.quoteDepth > 0, part.kind != .lineBreak, length > 0 else { continue }
            var valid = true
            text.enumerateAttribute(.paragraphStyle, in: range) { value, _, stop in
                guard let style = value as? NSParagraphStyle,
                      style.headIndent > 0 || style.firstLineHeadIndent > 0 else { valid = false; stop.pointee = true; return }
            }
            if !valid { return false }
        }
        return true
    }

    struct Run: Equatable, Sendable {
        let range: NSRange
        let bold: Bool
        let italic: Bool
        let strike: Bool
        let underline: Bool
        let highlight: Bool
        let script: Int
        let code: Bool
        let link: String?
        let inlineStyle: MarkdownInlineStyle?
    }
    struct Fragment: Sendable {
        struct StructuralPart: Sendable {
            enum Kind: Equatable, Sendable {
                case text, image, lineBreak, listItemStart, listItemEnd, emptyListItem
                case quoteStart, quoteEnd, headingStart, headingEnd, tableStart, tableEnd, cellStart, cellEnd, codeStart, codeEnd
                case taskMarker, thematicBreak
            }
            let text: String
            let quoteDepth: Int
            let listDepth: Int
            let headingLevel: Int?
            let tableCell: TableCell?
            let kind: Kind
        }
        struct TableCell: Sendable {
            let table: Int
            let row: Int
            let column: Int
        }
        struct RemoteImage: Sendable {
            let range: NSRange
            let url: URL
        }
        struct MathExpression: Sendable {
            let source: String
            let display: Bool
            let range: NSRange
        }
        struct MathImage: Sendable {
            let token: String
            let expressionIndex: Int
        }
        let text: String
        let html: String
        let runs: [Run]
        let imageLinks: [String?]
        let remoteImages: [RemoteImage]
        let structuralParts: [StructuralPart]
        let mathExpressions: [MathExpression]
        let mathImages: [MathImage]
        let hasUnverifiedHTMLBlocks: Bool

        init(text: String, html: String, runs: [Run], imageLinks: [String?] = [], remoteImages: [RemoteImage] = [], structuralParts: [StructuralPart] = [], mathExpressions: [MathExpression] = [], mathImages: [MathImage] = [], hasUnverifiedHTMLBlocks: Bool = false) {
            self.text = text
            self.html = html
            self.runs = runs
            self.imageLinks = imageLinks
            self.remoteImages = remoteImages
            self.structuralParts = structuralParts
            self.mathExpressions = mathExpressions
            self.mathImages = mathImages
            self.hasUnverifiedHTMLBlocks = hasUnverifiedHTMLBlocks
        }
    }

    static func resolveRemoteImages(_ fragment: Fragment, session: URLSession? = nil) async throws -> Fragment {
        var replacements: [(NSRange, String)] = []
        var downloaded: [URL: String] = [:]
        let downloader = MarkdownRemoteImageDownloader(session: session)
        for image in fragment.remoteImages {
            try Task.checkCancellation()
            let uri: String
            if let existing = downloaded[image.url] { uri = existing }
            else {
                let payload = try await downloader.download(image.url)
                uri = MarkdownImageUploadService.dataURI(payload, address: image.url.absoluteString)
                downloaded[image.url] = uri
            }
            replacements.append((image.range, uri))
        }
        try Task.checkCancellation()
        let html = NSMutableString(string: fragment.html)
        for (range, value) in replacements.reversed() { html.replaceCharacters(in: range, with: value) }
        return Fragment(text: fragment.text, html: html as String, runs: fragment.runs, imageLinks: fragment.imageLinks, structuralParts: fragment.structuralParts, mathExpressions: fragment.mathExpressions, mathImages: fragment.mathImages, hasUnverifiedHTMLBlocks: fragment.hasUnverifiedHTMLBlocks)
    }

    @MainActor
    private final class MathRenderJob {
        private var service: MathJaxRenderService?
        private var cancelled = false

        func cancel() {
            cancelled = true
            service?.cancel()
        }

        func render(_ fragment: Fragment, width: CGFloat, fontSize: CGFloat, dark: Bool,
                    physics: Bool, numbering: MarkdownMathNumbering) async throws -> [Data] {
            guard !cancelled else { throw CancellationError() }
            let expressions = fragment.mathExpressions.map { MathJaxRenderService.Expression(source: $0.source, display: $0.display) }
            let indices = fragment.mathImages.map(\.expressionIndex)
            return try await withCheckedThrowingContinuation { continuation in
                let service = MathJaxRenderService(expressions: expressions, outputIndices: indices, width: width,
                                                   dark: dark, fontSize: fontSize,
                                                   options: .init(physics: physics, numbering: numbering)) { [weak self] result in
                    self?.service = nil
                    switch result {
                    case let .failure(error): continuation.resume(throwing: error)
                    case let .success(images):
                        guard images.count == indices.count else { continuation.resume(throwing: MathJaxRenderService.RenderError.rendering); return }
                        var data: [Data] = []
                        for image in images {
                            guard let tiff = image?.tiffRepresentation, let bitmap = NSBitmapImageRep(data: tiff),
                                  let png = bitmap.representation(using: .png, properties: [:]) else {
                                continuation.resume(throwing: MathJaxRenderService.RenderError.rendering); return
                            }
                            data.append(png)
                        }
                        continuation.resume(returning: data)
                    }
                }
                self.service = service
                if cancelled { service.cancel() } else { service.start() }
            }
        }
    }

    static func resolveMath(_ fragment: Fragment, width: CGFloat, fontSize: CGFloat, dark: Bool,
                            physics: Bool, numbering: MarkdownMathNumbering) async throws -> Fragment {
        guard !fragment.mathImages.isEmpty else { return fragment }
        let job = await MathRenderJob()
        let images = try await withTaskCancellationHandler {
            try await job.render(fragment, width: width, fontSize: fontSize, dark: dark, physics: physics, numbering: numbering)
        } onCancel: {
            Task { @MainActor in job.cancel() }
        }
        try Task.checkCancellation()
        let html = NSMutableString(string: fragment.html)
        for (index, image) in fragment.mathImages.enumerated() {
            try Task.checkCancellation()
            let range = html.range(of: image.token)
            guard range.location != NSNotFound else { throw MathJaxRenderService.RenderError.rendering }
            let suffix = NSRange(location: NSMaxRange(range), length: html.length - NSMaxRange(range))
            guard html.range(of: image.token, options: .literal, range: suffix).location == NSNotFound else { throw MathJaxRenderService.RenderError.rendering }
            html.replaceCharacters(in: range, with: "data:image/png;base64," + images[index].base64EncodedString())
        }
        return Fragment(text: fragment.text, html: html as String, runs: fragment.runs, imageLinks: fragment.imageLinks,
                        structuralParts: fragment.structuralParts, hasUnverifiedHTMLBlocks: fragment.hasUnverifiedHTMLBlocks)
    }
    private struct Style {
        var bold = false, italic = false, strike = false, underline = false, highlight = false, code = false, keyboard = false
        var script = 0
        var link: String?
        var inlineStyle: MarkdownInlineStyle?
    }

    static func project(_ markdown: String, selection: NSRange, includeImages: Bool = false, documentURL: URL? = nil,
                        allowRemoteImages: Bool = false, syntax: MarkdownSyntaxOptions = .init(), detailsOpenOverrides: [NSRange: Bool] = [:]) -> Fragment? {
        let raw = markdown as NSString
        guard selection.location != NSNotFound, selection.length > 0,
              selection.location <= raw.length, selection.length <= raw.length - selection.location,
              !markdown.utf8.contains(0) else { return nil }
        func boundary(_ position: Int) -> Bool {
            position == 0 || position == raw.length ||
                !((0xd800...0xdbff).contains(raw.character(at: position - 1)) && (0xdc00...0xdfff).contains(raw.character(at: position)))
        }
        guard boundary(selection.location), boundary(NSMaxRange(selection)) else { return nil }
        var paths: MarkdownResourcePaths?
        var pathsLoaded = false
        let options = ((syntax.smartPunctuation ?? true) ? CMARK_OPT_SMART : 0) | CMARK_OPT_TABLE_SPANS | CMARK_OPT_HARDBREAKS | CMARK_OPT_FOOTNOTES
        let input = MarkdownPresentationParser.maskedFrontMatter(markdown, frontMatter: MarkdownPresentationParser.frontMatter(markdown))
        return MarkdownMathExtension.withDocument(input, options: options, includeInline: syntax.inlineMath, legacyInlineMath: syntax.legacyInlineMath, strictMode: syntax.strictMode, sourceForPositions: markdown, isCancelled: { Task.isCancelled }) { root, mathExtension, inline -> Fragment? in
            let source = MarkdownPresentationParser.Source(markdown, root: root, textOrigins: MarkdownMathExtension.textOrigins(in: mathExtension), looseHeadings: MarkdownMathExtension.looseHeadings(in: mathExtension), looseListRanges: MarkdownMathExtension.looseListRanges(in: mathExtension), isCancelled: { Task.isCancelled })
            let inlineByNode = Dictionary(uniqueKeysWithValues: inline.map { ($0.node, $0) })
            var cellPositions: [OpaquePointer: MarkdownPresentationParser.Source.TableCellPositions] = [:]
            var invalidCells: Set<OpaquePointer> = []
            func nodeRange(_ node: OpaquePointer) -> NSRange? {
                if let math = inlineByNode[node], let parent = cmark_node_parent(node) {
                    guard let range = source.mathInlineRange(line: math.line, column: math.column, byteLength: math.byteLength, parent: parent),
                          NSMaxRange(range) <= raw.length,
                          raw.substring(with: range).utf16.elementsEqual(("$" + math.text + "$").utf16) else { return nil }
                    return range
                }
                var parent = cmark_node_parent(node)
                while let current = parent {
                    if let name = cmark_node_get_type_string(current), String(cString: name) == "table_cell" {
                        if cellPositions[current] == nil && !invalidCells.contains(current) {
                            if let positions = source.tableCellPositions(current, isCancelled: { Task.isCancelled }) { cellPositions[current] = positions }
                            else { invalidCells.insert(current) }
                        }
                        guard let positions = cellPositions[current] else { return nil }
                        return source.tableInlineRange(node, positions: positions)
                    }
                    parent = cmark_node_parent(current)
                }
                return source.range(node)
            }
            var confirmedHTMLNodes = Set<OpaquePointer>()
            var allInlineHTML: [(OpaquePointer, NSRange?)] = []
            var rubyTags: [(parent: OpaquePointer, range: NSRange, closing: Bool)] = []
            var selectedHTMLBlockHasImage = false
            var svgBlockCandidates: [MarkdownPresentationParser.StandaloneSVG] = []
            var detailsCandidates: [(range: NSRange, proof: MarkdownHTMLMediaService.HTMLBlockCandidate, display: String, details: MarkdownHTMLMediaService.RichDetails)] = []
            var mathNodes: [(OpaquePointer, Fragment.MathExpression)] = []
            var mathContextValid = true
            if markdown.contains("$") || ["<strong", "<b", "<em", "<i", "<s", "<del", "<mark", "<sub", "<sup", "<u", "<a", "<kbd", "<span", "<ruby", "<audio", "<video", "<iframe", "<svg", "<details"].contains(where: { markdown.localizedCaseInsensitiveContains($0) }) {
                var context = MarkdownImageUploadService.HTMLContext(), stack = [root], lastHTMLPosition = 0, templateDepth = 0
                while let node = stack.popLast() {
                    if Task.isCancelled { return nil }
                    let kind = cmark_node_get_type(UnsafeMutablePointer<cmark_node>(node))
                    if kind == CMARK_NODE_TEXT && (context.inRawContext || templateDepth > 0) {
                        guard let range = source.range(node), NSIntersectionRange(range, selection).length == 0 else { return nil }
                    }
                    if kind == CMARK_NODE_HTML_INLINE || kind == CMARK_NODE_HTML_BLOCK {
                        if kind == CMARK_NODE_HTML_INLINE { allInlineHTML.append((node, nodeRange(node))) }
                        if kind == CMARK_NODE_HTML_BLOCK, let range = source.range(node), NSIntersectionRange(range, selection).length > 0,
                           let literal = cmark_node_get_literal(UnsafeMutablePointer<cmark_node>(node)), String(cString: literal).localizedCaseInsensitiveContains("<img") {
                            selectedHTMLBlockHasImage = true
                        }
                        if let range = nodeRange(node), range.location >= lastHTMLPosition,
                           MarkdownPresentationParser.htmlSourceMatches(node, range: range, text: raw, isCancelled: { Task.isCancelled }) {
                            let outsideTemplate = templateDepth == 0
                            let outside = context.consume(source: raw, range: range, isCancelled: { Task.isCancelled }, confirmedTag: { tag, name, closing in
                                if name == "template" { templateDepth = closing ? max(0, templateDepth - 1) : templateDepth + 1 }
                                if name == "ruby", let parent = cmark_node_parent(UnsafeMutablePointer<cmark_node>(node)) { rubyTags.append((OpaquePointer(parent), tag, closing)) }
                            })
                            if outside && outsideTemplate && templateDepth == 0 && kind == CMARK_NODE_HTML_INLINE {
                                confirmedHTMLNodes.insert(node)
                            }
                            if outside && outsideTemplate && templateDepth == 0 && kind == CMARK_NODE_HTML_BLOCK,
                               NSIntersectionRange(range, selection).length > 0, let literal = cmark_node_get_literal(UnsafeMutablePointer<cmark_node>(node)) {
                                let html = String(cString: literal)
                                if let svg = MarkdownPresentationParser.standaloneSVGBlockCandidate(node, range: range, text: raw, isCancelled: { Task.isCancelled }) {
                                    svgBlockCandidates.append(svg)
                                }
                                if let details = MarkdownHTMLMediaService.richDetails(html, isCancelled: { Task.isCancelled }),
                                   let display = MarkdownHTMLMediaService.editingHTMLBlock(html, isCancelled: { Task.isCancelled }),
                                   MarkdownHTMLMediaService.htmlBlockTagOffsets(node, range: range, tags: [], sourceText: raw, isCancelled: { Task.isCancelled }) != nil {
