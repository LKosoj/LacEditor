                            }
                            if let media = selectedMedia[current] {
                                var closing: OpaquePointer? = current
                                while let item = closing, item != end, item != media.closing {
                                    if Task.isCancelled { invalid = true; return }
                                    closing = cmark_node_next(item)
                                }
                                guard closing == media.closing else { invalid = true; return }
                                emitMedia(media, style: style)
                                if invalid { return }
                                child = cmark_node_next(media.closing)
                                continue
                            }
                            if let pair = pairByOpening[current] {
                                for range in [pair.openingRange, pair.closingRange] {
                                    let selected = NSIntersectionRange(selection, range)
                                    if selected.length > 0 && selected.length != range.length { invalid = true; return }
                                }
                                var styled = style
                                switch pair.kind {
                                case .strong: styled.bold = true
                                case .emphasis: styled.italic = true
                                case .strikethrough: styled.strike = true
                                case .underline: styled.underline = true
                                case .highlight: styled.highlight = true
                                case .subscriptText: styled.script = -1
                                case .superscriptText: styled.script = 1
                                case .keyboard: styled.keyboard = true
                                case .inlineStyle(let value): styled.inlineStyle = style.inlineStyle.map { value.inheriting($0) } ?? value
                                case .link:
                                    guard style.link == nil, let href = pair.href else { invalid = true; return }
                                    styled.link = href
                                default: invalid = true; return
                                }
                                visitSiblings(from: cmark_node_next(current), until: pair.closing, style: styled)
                                if invalid { return }
                                child = cmark_node_next(pair.closing)
                            } else {
                                visit(current, style: style)
                                child = cmark_node_next(current)
                            }
                        }
                    }
                    visitSiblings(from: cmark_node_first_child(node), until: nil, style: style)
                }
                if nodeType == CMARK_NODE_FOOTNOTE_REFERENCE {
                    guard let range = nodeRange(node) else { if mayIntersectSelection(node) { invalid = true }; return }
                    guard NSIntersectionRange(range, selection).length > 0 else { return }
                    guard selection.location <= range.location, NSMaxRange(selection) >= NSMaxRange(range),
                          let definition = cmark_node_parent_footnote_def(node), let marker = source.footnoteDefinitionMarker(definition),
                          let number = footnoteNumbers[definition], !number.isEmpty else { invalid = true; return }
                    let spelling = raw.substring(with: range), label = raw.substring(with: marker)
                    guard spelling == label else { invalid = true; return }
                    covered.append(range)
                    var superscript = style; superscript.script = 1
                    emit(number, sourceRange: range, style: superscript)
                    return
                }
                if nodeType == CMARK_NODE_FOOTNOTE_DEFINITION {
                    guard let marker = source.footnoteDefinitionMarker(node), let body = nodeRange(node),
                          let number = footnoteNumbers[node], NSMaxRange(marker) < raw.length,
                          NSMaxRange(body) >= NSMaxRange(marker) + 1,
                          raw.character(at: NSMaxRange(marker)) == 58 else {
                        if mayIntersectSelection(node) { invalid = true }; return
                    }
                    let whole = NSRange(location: marker.location, length: NSMaxRange(body) - marker.location)
                    guard NSIntersectionRange(whole, selection).length > 0 else { return }
                    guard selection.location <= whole.location, NSMaxRange(selection) >= NSMaxRange(whole) else { invalid = true; return }
                    let prefix = NSRange(location: marker.location, length: marker.length + 1)
                    covered.append(prefix)
                    emit("[\(number)] ", sourceRange: prefix, style: style)
                    var child = cmark_node_first_child(node)
                    while let current = child { visit(current, style: style); child = cmark_node_next(current) }
                    return
                }
                let type = String(cString: rawType)
                if (type == "paragraph" || type == "table"), let blockRange = nodeRange(node), NSIntersectionRange(blockRange, selection).length > 0 {
                    func verifyText(_ current: OpaquePointer) -> Bool {
                        if Task.isCancelled { return false }
                        if cmark_node_get_type(current) == CMARK_NODE_TEXT {
                            guard let literal = cmark_node_get_literal(current), let range = nodeRange(current),
                                  NSMaxRange(range) <= raw.length else { return false }
                            let spelling = raw.substring(with: range), value = String(cString: literal)
                            if spelling != value && MarkdownInlineTextProjection.pieces(spelling: spelling as NSString, literal: value,
                                sourceOffset: range.location, isCancelled: { Task.isCancelled }) == nil { return false }
                        }
                        var child = cmark_node_first_child(current)
                        while let next = child {
                            if !verifyText(next) { return false }
                            child = cmark_node_next(next)
                        }
                        return true
                    }
                    if !verifyText(node) { invalid = true; return }
                }
                if ["paragraph", "heading", "code_block", "thematic_break", "table"].contains(type) {
                    let range = type == "code_block" ? source.fenceRange(node) : nodeRange(node)
                    if let range { covered.append(range) }
                } else if type == "block_quote", let range = source.range(node) ?? source.fenceRange(node) {
                    quoteRanges.append(range)
                } else if type == "item" || type == "tasklist", let start = source.firstPosition(node), start < raw.length {
                    var end = start
                    let marker = raw.character(at: end)
                    if marker == 45 || marker == 43 || marker == 42 { end += 1 }
                    else {
                        while end < raw.length && (48...57).contains(raw.character(at: end)) { end += 1 }
                        if end > start && end < raw.length && (raw.character(at: end) == 46 || raw.character(at: end) == 41) { end += 1 }
                        else { end = start }
                    }
                    if end > start { covered.append(NSRange(location: start, length: end - start)) }
                    if type == "tasklist" {
                        while end < raw.length && (raw.character(at: end) == 32 || raw.character(at: end) == 9) { end += 1 }
                        if end + 2 < raw.length && raw.character(at: end) == 91 && raw.character(at: end + 2) == 93 &&
                            [32, 88, 120].contains(Int(raw.character(at: end + 1))) {
                            covered.append(NSRange(location: end, length: 3))
                        }
                    }
                }
                var next = style
                switch type {
                case "softbreak":
                    pendingSoftBreak = true
                    return
                case "linebreak":
                    pendingSoftBreak = false
                    return
                case "image":
                    guard mayIntersectSelection(node) else { return }
                    guard includeImages, let range = nodeRange(node),
                          selection.location <= range.location, NSMaxRange(selection) >= NSMaxRange(range),
                          let address = cmark_node_get_url(node) else { invalid = true; return }
                    let addressValue = String(cString: address)
                    var alt = ""
                    func appendAlt(_ item: OpaquePointer) {
                        guard let name = cmark_node_get_type_string(item) else { invalid = true; return }
                        switch String(cString: name) {
                        case "text", "code":
                            guard let value = cmark_node_get_literal(item) else { invalid = true; return }
                            alt += String(cString: value)
                        case "softbreak", "linebreak": alt += " "
                        case "image", "strong", "emph", "strikethrough":
                            var child = cmark_node_first_child(item)
                            while let current = child { appendAlt(current); child = cmark_node_next(current) }
                        default: invalid = true
                        }
                    }
                    appendAlt(node)
                    guard !invalid else { return }
                    let title = cmark_node_get_title(node).map { String(cString: $0) } ?? ""
                    emitImage(range: range, address: addressValue, alt: alt, title: title, css: "", style: style)
                    return
                case "thematic_break":
                    guard let parsedRange = source.range(node), let parent = cmark_node_parent(node) else { invalid = true; return }
                    let range: NSRange
                    if cmark_node_get_type(parent) == CMARK_NODE_BLOCK_QUOTE {
                        var end = parsedRange.location
                        while end < raw.length && raw.character(at: end) != 10 && raw.character(at: end) != 13 {
                            if Task.isCancelled { invalid = true; return }
                            end += 1
                        }
                        range = NSRange(location: parsedRange.location, length: end - parsedRange.location)
                    } else { range = parsedRange }
                    guard NSIntersectionRange(range, selection).length > 0 else { return }
                    let parentIsItem = cmark_node_get_type(parent) == CMARK_NODE_ITEM ||
                        cmark_node_get_type_string(parent).map({ String(cString: $0) == "tasklist" }) == true
                    guard (parent == root || cmark_node_get_type(parent) == CMARK_NODE_BLOCK_QUOTE || parentIsItem), selection.location <= range.location,
                          NSMaxRange(selection) >= NSMaxRange(range) else { invalid = true; return }
                    let precedingEnd = lastEnd ?? selection.location
                    if range.location > precedingEnd { appendBreaks(in: NSIntersectionRange(selection, NSRange(location: precedingEnd, length: range.location - precedingEnd))) }
                    if parentIsItem && output.hasSuffix("\n") { output += String(repeating: "  ", count: listDepth) }
                    output += "---"
                    html += "<hr>"
                    record("", kind: .thematicBreak)
                    hasStructuralOutput = true
                    lastEnd = NSMaxRange(range)
                    return
                case "heading":
                    guard let range = source.range(node) else { invalid = true; return }
                    guard NSIntersectionRange(range, selection).length > 0 else { return }
                    if selection.location <= range.location && NSMaxRange(selection) >= NSMaxRange(range) {
                        guard let parent = cmark_node_parent(node) else { invalid = true; return }
                        let parentIsItem = cmark_node_get_type(parent) == CMARK_NODE_ITEM ||
                            cmark_node_get_type_string(parent).map({ String(cString: $0) == "tasklist" }) == true
                        guard parent == root || cmark_node_get_type(parent) == CMARK_NODE_BLOCK_QUOTE || parentIsItem else { invalid = true; return }
                        let level = cmark_node_get_heading_level(node)
                        guard (1...6).contains(level) else { invalid = true; return }
                        let precedingEnd = lastEnd ?? selection.location
                        if range.location > precedingEnd { appendBreaks(in: NSIntersectionRange(selection, NSRange(location: precedingEnd, length: range.location - precedingEnd))) }
                        if parentIsItem && output.hasSuffix("\n") { output += String(repeating: "  ", count: listDepth) }
                        html += "<h\(level)>"
                        headingLevel = Int(level)
                        record("", kind: .headingStart)
                        lastEnd = range.location
                        visitInlineChildren(style: next)
                        record("", kind: .headingEnd)
                        headingLevel = nil
                        html += "</h\(level)>"
                        hasStructuralOutput = true
                        lastEnd = min(NSMaxRange(range), NSMaxRange(selection))
                        return
                    }
                case "block_quote":
                    let quoteRange = source.range(node) ?? source.fenceRange(node).flatMap { range in
                        range.location < raw.length && raw.character(at: range.location) == 62 ? range : nil
                    }
                    guard let range = quoteRange else { invalid = true; return }
                    guard NSIntersectionRange(range, selection).length > 0 else { return }
                    let whole = selection.location <= range.location && NSMaxRange(selection) >= NSMaxRange(range)
                    if whole {
                        guard let parent = cmark_node_parent(node),
                              (parent == root || cmark_node_get_type(parent) == CMARK_NODE_BLOCK_QUOTE ||
                               cmark_node_get_type(parent) == CMARK_NODE_ITEM ||
                               cmark_node_get_type_string(parent).map({ String(cString: $0) == "tasklist" }) == true),
                              NSMaxRange(range) <= raw.length else { invalid = true; return }
                        var paragraph = cmark_node_first_child(node)
                        while let current = paragraph {
                            let kind = cmark_node_get_type(current)
                            let name = cmark_node_get_type_string(current).map { String(cString: $0) }
                            guard kind == CMARK_NODE_PARAGRAPH || kind == CMARK_NODE_BLOCK_QUOTE || kind == CMARK_NODE_LIST || kind == CMARK_NODE_HEADING || kind == CMARK_NODE_CODE_BLOCK || kind == CMARK_NODE_THEMATIC_BREAK || name == "table" else { invalid = true; return }
                            paragraph = cmark_node_next(current)
                        }
                        let precedingEnd = lastEnd ?? selection.location
                        if range.location > precedingEnd { appendBreaks(in: NSIntersectionRange(selection, NSRange(location: precedingEnd, length: range.location - precedingEnd))) }
                        let parentIsItem = cmark_node_get_type(parent) == CMARK_NODE_ITEM ||
                            cmark_node_get_type_string(parent).map({ String(cString: $0) == "tasklist" }) == true
                        let indentation = parentIsItem ? String(repeating: "  ", count: listDepth) : ""
                        if !indentation.isEmpty && output.hasSuffix("\n") { output += indentation }
                        output += "> "
                        html += "<blockquote>"
                        quoteDepth += 1
                        record("", kind: .quoteStart)
                        lastEnd = range.location
                        let outputStart = (output as NSString).length, runStart = runs.count
                        visitContainerChildren(range, skipInitialMarker: false)
                        record("", kind: .quoteEnd)
                        quoteDepth -= 1
