                        let quoteText = original.substring(from: outputStart) as NSString
                        var breaks: [Int] = []
                        for index in 0..<quoteText.length where quoteText.character(at: index) == 10 { breaks.append(index) }
                        func extra(before offset: Int) -> Int {
                            var low = 0, high = breaks.count
                            while low < high { let middle = (low + high) / 2; if breaks[middle] < offset { low = middle + 1 } else { high = middle } }
                            return low * (2 + indentation.utf16.count)
                        }
                        for index in runStart..<runs.count {
                            let run = runs[index], start = run.range.location - outputStart, end = NSMaxRange(run.range) - outputStart
                            runs[index] = Run(range: NSRange(location: run.range.location + extra(before: start),
                                                            length: run.range.length + extra(before: end) - extra(before: start)),
                                              bold: run.bold, italic: run.italic, strike: run.strike, underline: run.underline, highlight: run.highlight, script: run.script, code: run.code, link: run.link, inlineStyle: run.inlineStyle)
                        }
                        output = original.substring(to: outputStart) + (quoteText as String).replacingOccurrences(of: "\n", with: "\n" + indentation + "> ")
                        html += "</blockquote>"
                        lastEnd = min(NSMaxRange(range), NSMaxRange(selection))
                        return
                    }
                    visitContainerChildren(range, skipInitialMarker: false)
                    return
                case "code_block":
                    guard mayIntersectSelection(node) else { return }
                    guard cmark_node_get_syntax_extension(node) != mathExtension,
                          let range = source.fenceRange(node), NSMaxRange(range) <= raw.length,
                          let literal = cmark_node_get_literal(node) else { invalid = true; return }
                    let info = cmark_node_get_fence_info(node).map { String(cString: $0) } ?? ""
                    guard let block = MarkdownPresentationParser.fencedCodeBlock(node, source: source, text: raw,
                        range: range, info: info, literal: String(cString: literal), isCancelled: { Task.isCancelled }) else { invalid = true; return }
                    func normalized(_ text: String) -> String { text.replacingOccurrences(of: "\r\n", with: "\n").replacingOccurrences(of: "\r", with: "\n") }
                    guard block.bodySegments.count == block.bodyPadding.count else { invalid = true; return }
                    let parts = zip(block.bodySegments, block.bodyPadding).compactMap { segment, padding -> (NSRange, Int)? in
                        let part = NSIntersectionRange(selection, segment)
                        let tabSelected = padding > 0 && segment.location > 0 && selection.location <= segment.location - 1 && NSMaxRange(selection) >= segment.location
                        return part.length > 0 || tabSelected ? (part, tabSelected ? padding : 0) : nil
                    }
                    let whole = selection.location <= block.range.location && NSMaxRange(selection) >= NSMaxRange(block.range)
                    guard !parts.isEmpty || whole else { return }
                    for (part, _) in parts where part.length > 0 {
                        let start = part.location, end = NSMaxRange(part)
                        if (start > 0 && raw.character(at: start - 1) == 13 && raw.character(at: start) == 10) ||
                           (end < raw.length && raw.character(at: end - 1) == 13 && raw.character(at: end) == 10) { invalid = true; return }
                    }
                    let precedingEnd = lastEnd ?? selection.location
                    if range.location > precedingEnd { appendBreaks(in: NSIntersectionRange(selection, NSRange(location: precedingEnd, length: range.location - precedingEnd))) }
                    let value = parts.map { part, padding in String(repeating: " ", count: padding) + (part.length > 0 ? normalized(raw.substring(with: part)) : "") }.joined()
                    let resultRange = NSRange(location: (output as NSString).length, length: (value as NSString).length)
                    output += value
                    record("", kind: .codeStart)
                    record(value)
                    record("", kind: .codeEnd)
                    if resultRange.length > 0 { runs.append(Run(range: resultRange, bold: false, italic: false, strike: false, underline: false, highlight: false, script: 0, code: true, link: nil, inlineStyle: nil)) }
                    let language = info.split(whereSeparator: { $0.isWhitespace }).first.map(String.init)
                    let attribute = language.map { " class=\"language-" + escape($0) + "\"" } ?? ""
                    html += "<pre><code" + attribute + ">" + escape(value) + "</code></pre>"
                    hasStructuralOutput = true
                    lastEnd = whole ? min(NSMaxRange(block.range), NSMaxRange(selection)) : parts.last.map { $0.0.length > 0 ? NSMaxRange($0.0) : selection.location + selection.length }
                    return
                case "list":
                    guard let listRange = nodeRange(node) else { invalid = true; return }
                    guard NSIntersectionRange(listRange, selection).length > 0 else { return }
                    if insideTable { invalid = true; return }
                    let wholeList = selection.location <= listRange.location && NSMaxRange(selection) >= NSMaxRange(listRange)
                    var items: [(OpaquePointer, Int)] = [], current = cmark_node_first_child(node), index = 0
                    while let item = current {
                        guard let range = source.range(item) else { invalid = true; return }
                        if wholeList || NSIntersectionRange(range, selection).length > 0 { items.append((item, index)) }
                        current = cmark_node_next(item)
                        index += 1
                    }
                    if wholeList || items.count > 1 {
                        let precedingEnd = lastEnd ?? selection.location
                        if listRange.location > precedingEnd {
                            let previousHTML = html
                            let previousPartCount = structuralParts.count
                            appendBreaks(in: NSIntersectionRange(selection, NSRange(location: precedingEnd, length: listRange.location - precedingEnd)))
                            if listDepth > 0 {
                                html = previousHTML
                                structuralParts.removeSubrange(previousPartCount..<structuralParts.count)
                            }
                        }
                        let ordered = cmark_node_get_list_type(node) == CMARK_ORDERED_LIST
                        let start = Int(cmark_node_get_list_start(node))
                        html += ordered ? "<ol start=\"\(start + (items.first?.1 ?? 0))\">" : "<ul>"
                        listDepth += 1
                        for (position, item) in items.enumerated() {
                            if position > 0 { output += "\n" }
                            output += String(repeating: "  ", count: listDepth - 1)
                            output += ordered ? "\(start + item.1). " : "• "
                            html += "<li>"
                            record("", kind: .listItemStart)
                            if let range = source.range(item.0) { lastEnd = max(range.location, selection.location) }
                            if let name = cmark_node_get_type_string(item.0), String(cString: name) == "tasklist" {
                                let checked = cmark_gfm_extensions_get_tasklist_item_checked(item.0)
                                output += checked ? "☑ " : "☐ "
                                html += checked ? "<input type=\"checkbox\" disabled checked> " : "<input type=\"checkbox\" disabled> "
                                record(checked ? "☑ " : "☐ ", kind: .taskMarker)
                            }
                            let partCount = structuralParts.count
                            visit(item.0, style: next)
                            if structuralParts.count == partCount { record("", kind: .emptyListItem) }
                            record("", kind: .listItemEnd)
                            html += "</li>"
                        }
                        listDepth -= 1
                        html += ordered ? "</ol>" : "</ul>"
                        lastEnd = min(NSMaxRange(listRange), NSMaxRange(selection))
                        return
                    }
                case "table":
                    guard let tableRange = nodeRange(node) else { invalid = true; return }
                    guard NSIntersectionRange(tableRange, selection).length > 0 else { return }
                    let wholeTable = selection.location <= tableRange.location && NSMaxRange(selection) >= NSMaxRange(tableRange)
                    let columnCount = Int(cmark_gfm_extensions_get_table_columns(node))
                    let alignments = cmark_gfm_extensions_get_table_alignments(node)
                    var selectedRows: [(Bool, [(OpaquePointer, Int)])] = []
                    var scan = cmark_node_first_child(node)
                    while let row = scan {
                        if !wholeTable, let rowRange = source.range(row), NSIntersectionRange(rowRange, selection).length == 0 {
                            scan = cmark_node_next(row)
                            continue
                        }
                        let header = cmark_node_get_type_string(row).map { String(cString: $0) == "table_header" } ?? false
                        var selectedCells: [(OpaquePointer, Int)] = [], cell = cmark_node_first_child(row), column = 0
                        while let current = cell {
                            if wholeTable { selectedCells.append((current, column)) }
                            else if let range = source.range(current), NSIntersectionRange(range, selection).length > 0 { selectedCells.append((current, column)) }
                            else if source.range(current) == nil,
                                    cmark_node_get_start_column(current) != 0 || cmark_node_get_end_column(current) != 0 { invalid = true; return }
                            cell = cmark_node_next(current)
                            column += 1
                        }
                        if !selectedCells.isEmpty { selectedRows.append((header, selectedCells)) }
                        scan = cmark_node_next(row)
                    }
                    let selectedCellCount = selectedRows.reduce(0) { $0 + $1.1.count }
                    if wholeTable || selectedCellCount > 1 {
                        let precedingEnd = lastEnd ?? selection.location
                        if tableRange.location > precedingEnd {
                            appendBreaks(in: NSIntersectionRange(selection, NSRange(location: precedingEnd, length: tableRange.location - precedingEnd)))
                        }
                        html += "<table>"
                        let tableIndex = tableCount
                        tableCount += 1
                        record("", kind: .tableStart)
                        hasStructuralOutput = true
                        insideTable = true
                        for (rowIndex, selectedRow) in selectedRows.enumerated() {
                            if rowIndex > 0 { output += "\n" }
                            html += "<tr>"
                            let header = selectedRow.0
                            for (column, selectedCell) in selectedRow.1.enumerated() {
                                if column > 0 { output += "\t" }
                                let tag = header ? "th" : "td"
                                let alignment: String
                                if let alignments, selectedCell.1 < columnCount {
                                    switch alignments[selectedCell.1] {
                                    case 108: alignment = " align=\"left\""
                                    case 99: alignment = " align=\"center\""
                                    case 114: alignment = " align=\"right\""
                                    default: alignment = ""
                                    }
                                } else { alignment = "" }
                                html += "<\(tag)\(alignment)>"
                                tableCell = .init(table: tableIndex, row: rowIndex, column: column)
                                record("", kind: .cellStart)
                                let partCount = structuralParts.count
                                visit(selectedCell.0, style: next)
                                if structuralParts.count == partCount { record("") }
                                record("", kind: .cellEnd)
                                tableCell = nil
                                html += header ? "</th>" : "</td>"
                            }
                            html += "</tr>"
                        }
                        insideTable = false
                        record("", kind: .tableEnd)
                        html += "</table>"
                        lastEnd = min(NSMaxRange(tableRange), NSMaxRange(selection))
                        return
                    }
                case "strong": next.bold = true
                case "emph": next.italic = true
                case "strikethrough":
                    if MarkdownPresentationParser.subscriptRange(node, source: source, text: raw) != nil {
                        next.script = -1
                    } else { next.strike = true }
                case "link":
                    guard mayIntersectSelection(node) else { return }
                    guard let url = cmark_node_get_url(node) else { invalid = true; return }
                    next.link = String(cString: url)
                    if let scheme = URLComponents(string: next.link ?? "")?.scheme?.lowercased(),
                       !["http", "https", "mailto"].contains(scheme) { invalid = true; return }
                case "text", "code":
                    guard let literal = cmark_node_get_literal(node) else { invalid = true; return }
                    next.code = type == "code"
                    if type == "text", let range = nodeRange(node), source.range(node) == range,
                       raw.substring(with: range) == String(cString: literal) {
                        let decorations = MarkdownPresentationParser.inlineDecorations(node, source: source, text: raw)
                        if !decorations.isEmpty {
                            var position = range.location
                            func emitIntersection(_ segment: NSRange, style: Style) {
                                let part = NSIntersectionRange(segment, selection)
                                if part.length > 0 { emit(raw.substring(with: part), sourceRange: part, style: style, collapseSpaces: true) }
                            }
                            for (decorated, kind) in decorations {
                                emitIntersection(NSRange(location: position, length: decorated.location - position), style: next)
                                let marker = kind == .highlight ? 2 : 1
                                var styled = next
                                if kind == .highlight { styled.highlight = true } else { styled.script = 1 }
                                emitIntersection(NSRange(location: decorated.location + marker, length: decorated.length - 2 * marker), style: styled)
                                position = NSMaxRange(decorated)
                            }
                            emitIntersection(NSRange(location: position, length: NSMaxRange(range) - position), style: next)
                            return
                        }
                    }
                    append(node, literal: String(cString: literal), style: next, isCode: next.code)
                    return
                case "custom_inline":
                    guard let index = mathIndices[node], !mathExpressions[index].display else {
                        if mayIntersectSelection(node) { invalid = true }; return
                    }
                    let range = mathExpressions[index].range
                    guard NSIntersectionRange(range, selection).length > 0 else { return }
                    guard selection.location <= range.location, NSMaxRange(selection) >= NSMaxRange(range) else { invalid = true; return }
                    let value = raw.substring(with: range)
                    let htmlStart = (html as NSString).length
                    emit(value, sourceRange: range, style: next)
                    guard !invalid else { return }
                    var token: String
                    repeat { token = "LACCOPYMATH" + UUID().uuidString.replacingOccurrences(of: "-", with: "") }
                    while markdown.contains(token) || html.contains(token)
                    let rendered = html as NSString
                    let match = rendered.range(of: escape(value), options: .backwards,
                                               range: NSRange(location: htmlStart, length: rendered.length - htmlStart))
                    guard match.location != NSNotFound else { invalid = true; return }
                    let replaced = NSMutableString(string: html)
                    replaced.replaceCharacters(in: match, with: "<img src=\"\(token)\" alt=\"\(escape(value))\">")
                    html = replaced as String
                    mathImages.append(.init(token: token, expressionIndex: index))
                    imageLinks.append(next.link)
                    hasStructuralOutput = true
                    return
                case "html_inline", "html_block":
                    if let details = selectedDetails[node] {
                        let open = detailsOpenOverrides[details.range] ?? details.details.initiallyOpen
                        guard let summary = detailsText(details.details.summaryHTML),
                              let body = open ? detailsText(details.details.bodyHTML) : "",
                              let document = try? SwiftSoup.parseBodyFragment(details.display),
                              let element = document.body()?.children().first(), element.tagName() == "details" else { invalid = true; return }
                        document.outputSettings().prettyPrint(pretty: false)
                        do {
                            if open { try element.attr("open", "") } else { try element.removeAttr("open") }
                        } catch { invalid = true; return }
                        guard let display = try? element.outerHtml() else { invalid = true; return }
                        let value = summary + (body.isEmpty ? "" : "\n" + body)
                        let precedingEnd = lastEnd ?? selection.location
                        if !insideTable && details.range.location > precedingEnd {
                            appendBreaks(in: NSIntersectionRange(selection, NSRange(location: precedingEnd, length: details.range.location - precedingEnd)))
                        }
                        output += value; record(value)
                        html += display
                        covered.append(details.range)
                        hasStructuralOutput = true; hasUnverifiedHTMLBlocks = true
                        lastEnd = NSMaxRange(details.range)
                        return
                    }
                    if let svg = selectedSVG[node] {
                        guard includeImages, svg.proof.closing == node else { invalid = true; return }
                        covered.append(svg.range)
                        emitImage(range: svg.range, address: "data:image/svg+xml;base64," + svg.data.base64EncodedString(), alt: "", title: "", css: "", style: style)
                        return
                    }
                    if let (range, frame) = selectedTwitter[node] {
                        let precedingEnd = lastEnd ?? selection.location
                        if !insideTable && range.location > precedingEnd {
                            appendBreaks(in: NSIntersectionRange(selection, NSRange(location: precedingEnd, length: range.location - precedingEnd)))
                        }
                        html += frame
                        covered.append(range)
                        hasStructuralOutput = true
                        hasUnverifiedHTMLBlocks = true
                        lastEnd = NSMaxRange(range)
                        return
                    }
                    if type == "html_block", let media = selectedMedia[node], media.closing == node {
                        guard let blockRange = nodeRange(node), media.range.location >= blockRange.location,
                              NSMaxRange(media.range) <= NSMaxRange(blockRange),
                              raw.substring(with: NSRange(location: blockRange.location, length: media.range.location - blockRange.location))
                                .trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
                              raw.substring(with: NSRange(location: NSMaxRange(media.range), length: NSMaxRange(blockRange) - NSMaxRange(media.range)))
                                .trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { invalid = true; return }
                        emitMedia(media, style: style)
                        return
                    }
                    if let (range, address, display) = htmlImages[node]?.first,
                       selection.location <= range.location, NSMaxRange(selection) >= NSMaxRange(range),
                       type == "html_inline" || selection == range {
                        covered.append(range)
                        emitImage(range: range, address: address, alt: display.alt,
                                  title: display.title ?? "", css: display.sizing.css, style: style)
                        return
                    }
                    if type == "html_block", let range = nodeRange(node), NSIntersectionRange(range, selection).length > 0,
                       emitNestedHTMLBlock(node, range: range, style: style) || emitHTMLBlock(node, range: range, style: style) { return }
                    if type == "html_inline", confirmedHTMLNodes.contains(node), let range = nodeRange(node),
                       NSMaxRange(range) <= raw.length,
                       ["<br>", "<br/>", "<br />"].contains(raw.substring(with: range).lowercased()) {
                        let selected = NSIntersectionRange(range, selection)
                        guard selected.length > 0 else { return }
                        guard selected == range else { invalid = true; return }
                        let precedingEnd = lastEnd ?? selection.location
                        if !insideTable && range.location > precedingEnd {
                            appendBreaks(in: NSIntersectionRange(selection, NSRange(location: precedingEnd, length: range.location - precedingEnd)))
                        }
                        output += "\n"
                        record("\n", kind: .lineBreak)
                        var fragment = "<br>"
                        if next.keyboard { fragment = "<kbd>" + fragment + "</kbd>" }
                        if next.strike { fragment = "<del>" + fragment + "</del>" }
                        if next.underline { fragment = "<u>" + fragment + "</u>" }
                        if next.highlight { fragment = "<mark>" + fragment + "</mark>" }
                        if next.script != 0 { let tag = next.script < 0 ? "sub" : "sup"; fragment = "<\(tag)>" + fragment + "</\(tag)>" }
                        if next.italic { fragment = "<em>" + fragment + "</em>" }
                        if next.bold { fragment = "<strong>" + fragment + "</strong>" }
                        if let inlineStyle = next.inlineStyle { fragment = "<span style=\"" + inlineStyle.editingCSS + "\">" + fragment + "</span>" }
                        if let link = next.link { fragment = "<a href=\"" + escape(link) + "\">" + fragment + "</a>" }
                        html += fragment
                        pendingSoftBreak = false
                        lastEnd = NSMaxRange(range)
                        return
                    }
                    if mayIntersectSelection(node) { invalid = true }
                    return
                default: break
                }
                if (type == "item" || type == "tasklist"), let range = nodeRange(node) {
                    guard NSIntersectionRange(range, selection).length > 0 else { return }
                    visitContainerChildren(range, skipInitialMarker: true)
                } else if type == "paragraph" {
                    if let prefix = source.referencePrefix(node) {
                        var ancestor = cmark_node_parent(node), hasList = false
                        while let current = ancestor {
                            if Task.isCancelled { invalid = true; return }
                            if cmark_node_get_type(current) == CMARK_NODE_ITEM { hasList = true }
                            ancestor = cmark_node_parent(current)
                        }
                        var structural: [Int: (end: Int, tab: Int?, padding: Int)] = [:]
                        if hasList && NSIntersectionRange(prefix, selection).length > 0 {
                            guard let proof = MarkdownPresentationParser.containerPrefixes(node, source: source, text: raw, isCancelled: { Task.isCancelled }) else { invalid = true; return }
                            let continuation = Array(proof.continuation.utf16)
                            let first = raw.lineRange(for: NSRange(location: prefix.location, length: 0))
                            var position = NSMaxRange(first)
                            while position < NSMaxRange(prefix) {
                                if Task.isCancelled { invalid = true; return }
                                let line = raw.lineRange(for: NSRange(location: position, length: 0))
                                var offset = 0, cursor = position, column = 0, tab: Int?, padding = 0
                                while offset < continuation.count {
                                    if Task.isCancelled { invalid = true; return }
                                    guard cursor < NSMaxRange(line) else { invalid = true; return }
                                    let unit = raw.character(at: cursor)
                                    if unit == 9 && continuation[offset] == 32 {
                                        let next = (column / 4 + 1) * 4
                                        let count = next - column
                                        let available = min(count, continuation.count - offset)
                                        guard continuation[offset..<(offset + available)].allSatisfy({ $0 == 32 }) else { invalid = true; return }
                                        offset += available
                                        if count > available { tab = cursor; padding = count - available }
                                        column = next
                                    } else {
                                        guard unit == continuation[offset] else { invalid = true; return }
                                        offset += 1
                                        column = unit == 9 ? (column / 4 + 1) * 4 : column + 1
                                    }
                                    cursor += 1
                                }
                                structural[position] = (cursor, tab, padding)
                                position = NSMaxRange(line)
                            }
                        }
                        emitUnrepresented(prefix, quotePrefixes: sourceQuoteDepth, structuralPrefixes: structural)
                    }
                    pendingSoftBreak = false
                    defer { pendingSoftBreak = false }
                    visitInlineChildren(style: next)
                } else if ["heading", "strong", "emph", "link", "strikethrough", "table_cell"].contains(type) {
                    visitInlineChildren(style: next)
                } else {
                    var child = cmark_node_first_child(node)
                    while let current = child { visit(current, style: next); child = cmark_node_next(current) }
                }
            }
            var rootNodes: [(OpaquePointer, NSRange)] = []
            var rootNode = cmark_node_first_child(root), rootOrderKnown = true, hasSelectedDefinition = false
            while let node = rootNode {
                if Task.isCancelled { return nil }
                let marker = cmark_node_get_type(node) == CMARK_NODE_FOOTNOTE_DEFINITION ? source.footnoteDefinitionMarker(node) : nil
                let range = cmark_node_get_type(node) == CMARK_NODE_CODE_BLOCK ? source.fenceRange(node) : nodeRange(node)
                if let range {
                    let whole = marker.map { NSUnionRange($0, range) } ?? range
                    if marker != nil && NSIntersectionRange(whole, selection).length > 0 { hasSelectedDefinition = true }
                    rootNodes.append((node, whole))
                } else { rootOrderKnown = false }
                rootNode = cmark_node_next(node)
            }
            let orderedNodes = rootNodes.sorted { $0.1.location < $1.1.location }
            var precedingEnd = 0
            for (_, range) in orderedNodes {
                if range.location < precedingEnd { rootOrderKnown = false; break }
                precedingEnd = NSMaxRange(range)
            }
            if rootOrderKnown {
                var sourceCursor = 0
                for (node, range) in orderedNodes {
                    if Task.isCancelled { return nil }
                    if sourceCursor < range.location { emitUnrepresented(NSRange(location: sourceCursor, length: range.location - sourceCursor)) }
                    visit(node, style: Style())
                    sourceCursor = NSMaxRange(range)
                }
                if sourceCursor < raw.length { emitUnrepresented(NSRange(location: sourceCursor, length: raw.length - sourceCursor)) }
            } else if hasSelectedDefinition { return nil
            } else { visit(root, style: Style()) }
            let orderedCoverage = covered.sorted { $0.location < $1.location }
            let quotes = quoteRanges.sorted { $0.location < $1.location }
            var quoteEnds: [Int] = [], maxQuoteEnd = 0
            for range in quotes { maxQuoteEnd = max(maxQuoteEnd, NSMaxRange(range)); quoteEnds.append(maxQuoteEnd) }
            var quoteLine = NSRange(location: NSNotFound, length: 0), quoteChecked = 0, quotePrefixValid = true
            func isQuoteMarker(_ offset: Int) -> Bool {
                var low = 0, high = quotes.count
                while low < high {
                    let middle = (low + high) / 2
                    if quotes[middle].location <= offset { low = middle + 1 } else { high = middle }
                }
                guard low > 0, quoteEnds[low - 1] > offset else { return false }
                if quoteLine.location == NSNotFound || offset >= NSMaxRange(quoteLine) {
                    quoteLine = raw.lineRange(for: NSRange(location: offset, length: 0))
                    quoteChecked = quoteLine.location
                    quotePrefixValid = true
                }
                while quoteChecked < offset {
                    if Task.isCancelled { return false }
                    let unit = raw.character(at: quoteChecked)
                    if unit != 32 && unit != 9 && unit != 62 { quotePrefixValid = false }
                    quoteChecked += 1
                }
                return quotePrefixValid
            }
            var cursor = selection.location
            for range in orderedCoverage {
                if Task.isCancelled { return nil }
                let end = min(NSMaxRange(selection), range.location)
                while cursor < end {
                    if Task.isCancelled { return nil }
                    let unit = raw.character(at: cursor)
                    if unit != 32 && unit != 9 && unit != 10 && unit != 13 && !(unit == 62 && isQuoteMarker(cursor)) { return nil }
                    cursor += 1
                }
                cursor = max(cursor, min(NSMaxRange(selection), NSMaxRange(range)))
                if cursor == NSMaxRange(selection) { break }
            }
            while cursor < NSMaxRange(selection) {
                if Task.isCancelled { return nil }
                let unit = raw.character(at: cursor)
                if unit != 32 && unit != 9 && unit != 10 && unit != 13 && !(unit == 62 && isQuoteMarker(cursor)) { return nil }
                cursor += 1
            }
            if let lastEnd, lastEnd < NSMaxRange(selection) {
                appendBreaks(in: NSRange(location: lastEnd, length: NSMaxRange(selection) - lastEnd))
            }
            if lastEnd == nil, raw.substring(with: selection).allSatisfy({ $0 == "\r" || $0 == "\n" }) {
                appendBreaks(in: selection)
            }
            guard !invalid, (mathImages.isEmpty || mathContextValid), !output.isEmpty || hasStructuralOutput else { return nil }
            return Fragment(text: output, html: html, runs: runs, imageLinks: imageLinks, remoteImages: remoteImages, structuralParts: structuralParts,
                            mathExpressions: mathExpressions, mathImages: mathImages, hasUnverifiedHTMLBlocks: hasUnverifiedHTMLBlocks)
        } ?? nil
    }
